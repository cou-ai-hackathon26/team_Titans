import { toBanglaDigits } from '../engine/banglaCompiler';
import type { DecodedMedication, PatientContext } from '../types/clinical';

/**
 * Renders a high-contrast printable Sun/Moon Visual Caregiver Schedule Card to PNG
 * for elderly Bangladeshi patients and WhatsApp family sharing.
 */
export function downloadCaregiverCardPng(
  prescriptionId: string,
  patientContext: PatientContext,
  medications: DecodedMedication[],
  totalMrpBdt: number,
): void {
  const rowHeight = 112;
  const headerHeight = 156;
  const colHeaderHeight = 56;
  const footerHeight = 84;
  const width = 1080;
  const height = headerHeight + colHeaderHeight + Math.max(1, medications.length) * rowHeight + footerHeight;

  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  // Crisp white card background
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, width, height);

  // Header band
  ctx.fillStyle = '#0f766e';
  ctx.fillRect(0, 0, width, headerHeight);

  ctx.fillStyle = '#ffffff';
  ctx.font = '700 32px "Plus Jakarta Sans", sans-serif';
  ctx.fillText('OshudhGuard AI — ওষুধ খাওয়ার সময়সূচী', 40, 56);

  ctx.fillStyle = '#ccfbf1';
  ctx.font = '500 18px "DM Sans", sans-serif';
  const patientLabel = patientContext.patientName
    ? `${patientContext.patientName} (${patientContext.age ?? '—'}y)`
    : 'Outpatient Caregiver Card';
  ctx.fillText(
    `Patient: ${patientLabel}  ·  Rx ID: ${prescriptionId}  ·  DGDA Est. MRP: ৳${totalMrpBdt.toFixed(0)}`,
    40,
    98,
  );
  ctx.fillText(
    'Sun/Moon Zero-Literacy Caregiver Guide · Verify with Pharmacist before changing doses',
    40,
    130,
  );

  // Column header bar
  const colY = headerHeight;
  ctx.fillStyle = '#f1f5f9';
  ctx.fillRect(0, colY, width, colHeaderHeight);
  ctx.strokeStyle = '#cbd5e1';
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.moveTo(0, colY + colHeaderHeight);
  ctx.lineTo(width, colY + colHeaderHeight);
  ctx.stroke();

  ctx.fillStyle = '#0f172a';
  ctx.font = '700 18px "Plus Jakarta Sans", sans-serif';
  ctx.fillText('Medicine / ওষুধ', 40, colY + 35);
  ctx.fillStyle = '#b45309';
  ctx.fillText('সকাল (Morning)', 490, colY + 35);
  ctx.fillStyle = '#0369a1';
  ctx.fillText('দুপুর (Noon)', 690, colY + 35);
  ctx.fillStyle = '#312e81';
  ctx.fillText('রাত (Night)', 875, colY + 35);

  // Medication rows
  medications.forEach((med, index) => {
    const y = colY + colHeaderHeight + index * rowHeight;
    if (index % 2 === 1) {
      ctx.fillStyle = '#f8fafc';
      ctx.fillRect(0, y, width, rowHeight);
    }

    ctx.strokeStyle = '#e2e8f0';
    ctx.beginPath();
    ctx.moveTo(0, y + rowHeight);
    ctx.lineTo(width, y + rowHeight);
    ctx.stroke();

    // Brand + strength
    ctx.fillStyle = '#0f172a';
    ctx.font = '700 22px "Plus Jakarta Sans", sans-serif';
    ctx.fillText(
      `${med.resolvedDrug.brandName} ${med.resolvedDrug.strengthText} (${med.resolvedDrug.banglaName})`,
      40,
      y + 38,
    );

    ctx.fillStyle = '#475569';
    ctx.font = '500 15px "DM Sans", sans-serif';
    ctx.fillText(
      `${med.resolvedDrug.activeGenericDisplay} · ${med.compiledSchedule.banglaTimingLabel} · ${toBanglaDigits(med.compiledSchedule.durationDays)} দিন`,
      40,
      y + 66,
    );

    ctx.fillStyle = '#0f766e';
    ctx.font = '600 15px "Hind Siliguri", sans-serif';
    ctx.fillText(med.compiledSchedule.banglaVoiceText.slice(0, 72), 40, y + 92);

    // Draw visual pill dots for Morning / Noon / Night
    const drawSlot = (count: number, centerX: number, fillHex: string) => {
      if (count <= 0) {
        ctx.fillStyle = '#cbd5e1';
        ctx.font = '600 24px "JetBrains Mono", monospace';
        ctx.fillText('—', centerX - 8, y + 64);
        return;
      }
      const dots = Math.min(4, Math.ceil(count));
      const spacing = 26;
      const startX = centerX - ((dots - 1) * spacing) / 2;
      for (let d = 0; d < dots; d++) {
        ctx.beginPath();
        ctx.arc(startX + d * spacing, y + 48, 10, 0, Math.PI * 2);
        ctx.fillStyle = fillHex;
        ctx.fill();
      }
      ctx.fillStyle = '#0f172a';
      ctx.font = '700 16px "JetBrains Mono", monospace';
      ctx.fillText(`${toBanglaDigits(count)} টি`, centerX - 18, y + 84);
    };

    drawSlot(med.compiledSchedule.morning, 555, '#d97706');
    drawSlot(med.compiledSchedule.noon, 745, '#0284c7');
    drawSlot(med.compiledSchedule.night, 930, '#4338ca');
  });

  // Footer
  const footY = height - footerHeight;
  ctx.fillStyle = '#f8fafc';
  ctx.fillRect(0, footY, width, footerHeight);
  ctx.fillStyle = '#475569';
  ctx.font = '500 15px "DM Sans", sans-serif';
  ctx.fillText(
    'Generated by OshudhGuard AI — Bangladeshi Prescription Decoder & Clinical Safety Assistant',
    40,
    footY + 48,
  );

  const link = document.createElement('a');
  link.download = `OshudhGuard-Card-${prescriptionId}.png`;
  link.href = canvas.toDataURL('image/png');
  link.click();
}
